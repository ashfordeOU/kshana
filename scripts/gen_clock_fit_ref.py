"""Write the `[clock_fit]` comparison pre-registered in tests/fixtures/clock_fit/PREREGISTRATION.md
(and its Addendum 1).

    python3 -m venv /tmp/v && /tmp/v/bin/pip install allantools==2024.6 numpy
    scripts/fetch_cs5071a.sh                                   # D2, git-ignored
    /tmp/v/bin/python -I scripts/gen_clock_fit_ref.py

Nine synthetic records of known power-law noise (C1 white FM, C2 random-walk FM, C3 both, seeds
20261101 to 20261103, 131 072 phase samples at tau0 = 1 s) are written as TimeLab-style logs into
realdata-cache/clock_fit/ (git-ignored: 9 MB of seeded noise, regenerated by this script). The generator
is built from the closed forms of the Allan deviation of power-law noise (IEEE Std 1139), not from the
engine, and is checked against theory by allantools `oadev` before anything is compared: that check is
printed and recorded in RESULTS.md, it is not a bar of the engine.

reference.json holds the truth coefficients, the SHA-256 of each record's phase samples, and allantools'
lag-1 noise identification (`noise_id`, dmin = 0, dmax = 2, phase data, the record's least-squares quadratic
removed) at every octave averaging factor, for the nine records and for two measured ones: D2 (the first
65 536 readings of the 5071A caesium clock) and D3 (the IGS clock of satellite G01).
"""
import argparse
import hashlib
import json
import math
import os
import struct
import sys

import allantools
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

N = 131072
TAU0 = 1.0
SEEDS = (20261101, 20261102, 20261103)
H0 = 1.8e-19  # white FM: 2 sigma_y(1 s)^2 with sigma_y(1 s) = 3e-10 (SA.45s)
HM2 = 1.52e-29  # random-walk FM: 3 sigma_y(1e4 s)^2 / (2 pi^2 1e4 s) with sigma_y = 1e-12
PI = math.pi


def record(config, seed):
    rng = np.random.default_rng(seed)
    y = np.zeros(N)
    if config in (1, 3):
        y += rng.standard_normal(N) * math.sqrt(H0 / (2 * TAU0))
    if config in (2, 3):
        y += np.cumsum(rng.standard_normal(N) * math.sqrt(2 * PI**2 * HM2 * TAU0))
    x = np.concatenate([[0.0], np.cumsum(y[:-1]) * TAU0])
    return x


def truth_adev(tau, config):
    v = 0.0
    if config in (1, 3):
        v += H0 / (2 * tau)
    if config in (2, 3):
        v += (2 * PI**2 / 3) * HM2 * tau
    return math.sqrt(v)


def sha_f64(x):
    return hashlib.sha256(struct.pack(f"<{len(x)}d", *x)).hexdigest()


def write_log(path, x):
    with open(path, "w", newline="\n") as f:
        f.write("# synthetic power-law noise written by scripts/gen_clock_fit_ref.py\n# tau0 = 1\n# units = s\n")
        for v in x:
            f.write(f"{v:.17g}\n")


def alphas(x, tau0=TAU0):
    """allantools lag-1 noise identification at octave averaging factors, on the detrended record."""
    x = np.asarray(x)
    t = np.arange(len(x)) * tau0
    c = np.polyfit(t, x, 2)
    d = x - np.polyval(c, t)
    out = []
    m = 1
    while len(d) // m >= 32:
        try:
            a = allantools.noise_id(d, m, dmin=0, dmax=2, data_type="phase")
        except Exception:  # noqa: BLE001
            a = None
        out.append([m, None if a is None else int(a[0]) if isinstance(a, tuple) else int(a)])
        m *= 2
    return out


def read_series(path, n=None):
    out = []
    for line in open(path, encoding="utf-8"):
        s = line.strip()
        if s and not s.startswith("#"):
            out.append(float(s))
            if n and len(out) == n:
                break
    return out


def main():
    global N
    ap = argparse.ArgumentParser()
    ap.add_argument("--cache", default=os.path.join(ROOT, "realdata-cache/clock_fit"))
    ap.add_argument("--cs5071a", default=os.path.join(ROOT, "realdata-cache/cs5071a/5071A_phase.txt"))
    ap.add_argument("--fixtures", default=os.path.join(ROOT, "tests/fixtures/clock_fit"))
    ap.add_argument("--clock-real-ref", default=os.path.join(ROOT, "tests/fixtures/clock_log_real/reference.json"))
    a = ap.parse_args()
    os.makedirs(a.cache, exist_ok=True)
    ref = {"generator": "scripts/gen_clock_fit_ref.py", "allantools": allantools.__version__,
           "numpy": np.__version__, "h0": H0, "h_m2": HM2, "n": N, "tau0": TAU0, "records": {}}
    worst = 0.0
    for cfg in (1, 2, 3):
        for seed in SEEDS:
            x = record(cfg, seed)
            name = f"fit_C{cfg}_{seed}.txt"
            write_log(os.path.join(a.cache, name), x.tolist())
            # the generator check: allantools oadev against the closed form (not a bar of the engine)
            taus = [1, 8, 64] if cfg == 1 else [64, 512, 4096] if cfg == 2 else [1, 8, 64, 512, 4096]
            tt, dev, _, _ = allantools.oadev(x, rate=1.0, data_type="phase", taus=[float(t) for t in taus])
            chk = []
            for t, d in zip(tt, dev):
                r = d / truth_adev(t, cfg)
                chk.append([float(t), float(r)])
                worst = max(worst, abs(r - 1))
            print(f"{name}: oadev/theory {[(int(t), round(r, 3)) for t, r in chk]}")
            ref["records"][name] = {
                "config": cfg, "seed": seed,
                "h0": H0 if cfg in (1, 3) else 0.0, "h_m2": HM2 if cfg in (2, 3) else 0.0,
                "phase_sha256": sha_f64(x.tolist()), "alphas": alphas(x),
                "generator_check": chk,
            }
    print(f"generator check: largest |oadev/theory - 1| = {worst:.3f} (registered limit 0.20"
          f"{'' if worst <= 0.20 else ': NOT met; sampling scatter at tau = 4096, see the long-record diagnostic'})")
    # Diagnostic added after the registered check missed at tau = 4096 (RESULTS.md): the same generator on
    # a record 16 times longer, where the sampling scatter of the Allan deviation is a quarter of that.
    n_keep, N = N, 2**21
    xl = record(3, 20261101)
    N = n_keep
    tl = [1.0, 8.0, 64.0, 512.0, 4096.0]
    _, dl, _, _ = allantools.oadev(xl, rate=1.0, data_type="phase", taus=tl)
    long_chk = [[t, float(d / truth_adev(t, 3))] for t, d in zip(tl, dl)]
    print("long-record diagnostic (C3, seed 20261101, 2^21 samples): oadev/theory",
          [(int(t), round(r, 3)) for t, r in long_chk])
    ref["generator_long_record_check"] = {"n": 2**21, "config": 3, "seed": 20261101, "oadev_over_theory": long_chk}
    long_worst = max(abs(r - 1) for _, r in long_chk)
    # measured records: D2 and D3
    d2 = read_series(a.cs5071a, 65536)
    ref["records"]["D2"] = {"phase_sha256": sha_f64(d2), "alphas": alphas(d2)}
    real = json.load(open(a.clock_real_ref))
    d3 = real["cases"]["igs_clk_30s_2026214_G01_ABMF.clk:G01"]["phase_s"]
    # D3 is at tau0 = 30 s: identify with that spacing (allantools sees the same phase and af)
    ref["records"]["D3"] = {"phase_sha256": sha_f64(d3), "alphas": alphas(d3, 30.0), "tau0": 30.0}
    os.makedirs(a.fixtures, exist_ok=True)
    with open(os.path.join(a.fixtures, "reference.json"), "w") as f:
        json.dump(ref, f, indent=1)
        f.write("\n")
    if long_worst > 0.10:
        sys.exit("generator check failed: the long record does not match theory")


if __name__ == "__main__":
    main()
