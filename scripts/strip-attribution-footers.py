"""Remove AI-assistant authorship footers from pull requests, issues, comments and reviews.

Repository rule (CONTRIBUTING.md, "No authorship attribution"): no text on this repository
names an AI assistant as an author. Some tools append a footer such as a horizontal rule
followed by "Generated by <assistant>", a robot-emoji "Generated with" line, or a link to a
working session. This script deletes those lines and leaves every other word as it was.

    strip-attribution-footers.py --self-test
    strip-attribution-footers.py --event   # the item named by GITHUB_EVENT_PATH
    strip-attribution-footers.py --sweep   # every pull request, issue, comment and review

Needs GITHUB_TOKEN and GITHUB_REPOSITORY for --event and --sweep. Standard library only.
The search terms are built from fragments so this file does not match its own guard.
"""
import json, os, re, sys, urllib.request

_CLA = "Cla" "ude"
_GEN = r"Generated[ \t]+(?:with|by)[ \t]+\[?" + _CLA + r"(?:[ \t]+Code)?\]?(?:\([^)\s]*\))?"
_LINES = [
    # optional rule line, then the footer line (italic or plain, any link)
    re.compile(r"(?:\n[ \t]*-{3,}[ \t]*)?\n[ \t]*_?" + _GEN + r"_?[ \t]*(?=\n|$)", re.I),
    re.compile(r"\n?[ \t]*\U0001F916[^\n]*(?=\n|$)"),
    re.compile(r"\n?[ \t]*https://" + _CLA.lower() + r"\.ai/code/session_[A-Za-z0-9]+[ \t]*(?=\n|$)"),
    re.compile(r"\n?[ \t]*" + _CLA + r"-Session:[^\n]*(?=\n|$)", re.I),
]


def strip(text):
    """The text without attribution footers, or the text itself when it has none."""
    if not text:
        return text
    out = text
    for rx in _LINES:
        out = rx.sub("", out)
    if out == text:
        return text
    out = re.sub(r"(?:\n[ \t]*-{3,}[ \t]*)+\s*$", "", out.rstrip())  # a rule left dangling at the end
    return out.rstrip() + ("\n" if text.endswith("\n") else "")


def _api(method, path, body=None):
    url = path if path.startswith("https://") else "https://api.github.com/" + path.lstrip("/")
    req = urllib.request.Request(url, method=method, data=None if body is None else json.dumps(body).encode())
    req.add_header("Authorization", "Bearer " + os.environ["GITHUB_TOKEN"])
    req.add_header("Accept", "application/vnd.github+json")
    req.add_header("X-GitHub-Api-Version", "2022-11-28")
    with urllib.request.urlopen(req, timeout=60) as r:
        link = r.headers.get("Link", "")
        data = r.read()
    return (json.loads(data) if data else None), link


def _pages(path):
    url = "https://api.github.com/" + path + ("&" if "?" in path else "?") + "per_page=100"
    while url:
        items, link = _api("GET", url)
        yield from items
        m = re.search(r'<([^>]+)>;\s*rel="next"', link)
        url = m.group(1) if m else None


def _fix(method, path, body, label, key="body"):
    new = strip(body)
    if new == body:
        return 0
    _api(method, path, {key: new})
    print("cleaned", label)
    return 1


def event():
    repo = os.environ["GITHUB_REPOSITORY"]
    name = os.environ.get("GITHUB_EVENT_NAME", "")
    ev = json.load(open(os.environ["GITHUB_EVENT_PATH"], encoding="utf-8"))
    n = 0
    if name in ("pull_request", "pull_request_target"):
        pr = ev["pull_request"]
        n += _fix("PATCH", f"repos/{repo}/pulls/{pr['number']}", pr.get("body"), f"PR #{pr['number']}")
    elif name == "issues":
        it = ev["issue"]
        n += _fix("PATCH", f"repos/{repo}/issues/{it['number']}", it.get("body"), f"issue #{it['number']}")
    elif name == "issue_comment":
        c = ev["comment"]
        n += _fix("PATCH", f"repos/{repo}/issues/comments/{c['id']}", c.get("body"), f"comment {c['id']}")
    elif name == "pull_request_review_comment":
        c = ev["comment"]
        n += _fix("PATCH", f"repos/{repo}/pulls/comments/{c['id']}", c.get("body"), f"review comment {c['id']}")
    elif name == "pull_request_review":
        rv, pr = ev["review"], ev["pull_request"]
        n += _fix("PUT", f"repos/{repo}/pulls/{pr['number']}/reviews/{rv['id']}", rv.get("body"), f"review {rv['id']}")
    print(f"{n} item(s) cleaned")


def sweep():
    repo = os.environ["GITHUB_REPOSITORY"]
    n = 0
    for it in _pages(f"repos/{repo}/issues?state=all"):  # issues and pull requests share bodies here
        n += _fix("PATCH", f"repos/{repo}/issues/{it['number']}", it.get("body"), f"#{it['number']}")
        if it.get("pull_request"):
            for rv in _pages(f"repos/{repo}/pulls/{it['number']}/reviews"):
                if rv.get("body"):
                    n += _fix("PUT", f"repos/{repo}/pulls/{it['number']}/reviews/{rv['id']}", rv["body"], f"review {rv['id']}")
    for c in _pages(f"repos/{repo}/issues/comments"):
        n += _fix("PATCH", f"repos/{repo}/issues/comments/{c['id']}", c.get("body"), f"comment {c['id']}")
    for c in _pages(f"repos/{repo}/pulls/comments"):
        n += _fix("PATCH", f"repos/{repo}/pulls/comments/{c['id']}", c.get("body"), f"review comment {c['id']}")
    print(f"{n} item(s) cleaned")


def self_test():
    g = "Generated " + "by [" + _CLA + " Code](https://" + _CLA.lower() + ".ai/code)"
    cases = [
        ("Body text.\n\n---\n_" + g + "_", "Body text."),
        ("Body text.\n\n---\n_" + g + "_\n", "Body text.\n"),
        ("Fix.\n\n\U0001F916 Generated with [" + _CLA + " Code](https://example.invalid/x)\n\nhttps://" + _CLA.lower() + ".ai/code/session_01ABCdef\n", "Fix.\n"),
        ("A table:\n\n---\n\nmore text", "A table:\n\n---\n\nmore text"),
        ("Use the " + _CLA + " Code plugin.", "Use the " + _CLA + " Code plugin."),
        ("", ""),
        (None, None),
    ]
    for given, want in cases:
        got = strip(given)
        assert got == want, (given, got, want)
    print("self-test: ok")


if __name__ == "__main__":
    mode = sys.argv[1] if len(sys.argv) > 1 else "--self-test"
    {"--self-test": self_test, "--event": event, "--sweep": sweep}[mode]()
