"""Generate src/interconnect/mavlink_table.rs: CRC_EXTRA and maximum payload length of every
MAVLink message defined in the official definitions (message_definitions/v1.0/all.xml and the files
it includes, recursively).

Usage: python3 scripts/gen_mavlink_table.py <path to a mavlink/mavlink checkout> [--out FILE]

The CRC_EXTRA of a message is the X.25 CRC (CRC-16/MCRF4XX, initial 0xFFFF) of the message name and
a space, then, for each field of the original message (extensions excluded) in wire order (fields
sorted by type size, largest first, keeping their order within a size), the field's base type and a
space, the field's name and a space, and for an array its length as one octet; the 16-bit CRC is
folded to one octet as (crc & 0xFF) ^ (crc >> 8). (MAVLink serialization guide, "CRC_EXTRA
calculation".) The maximum payload length is the sum of every field's size times its array length,
extensions included.

Only numbers are written (message id, CRC_EXTRA, maximum length), each row with the message's name as
a comment. The XML is not copied. The
checkout's commit is recorded in the generated file.

Source: github.com/mavlink/mavlink, generated from commit 3fbb88560a06867b1d4987e194e3309fa141cfd4
(2026-11-19). Licence of the source (its COPYING): the MAVLink generator is (L)GPL v3, with an
exception that licenses generator output embedded in a product under the MIT licence. This script is
kshana's own (AGPL-3.0-only) and writes only per-message numbers computed from the definitions and the
message names; no definition text and no upstream code is copied into kshana.
"""
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

SIZES = {
    "char": 1, "int8_t": 1, "uint8_t": 1,
    "int16_t": 2, "uint16_t": 2,
    "int32_t": 4, "uint32_t": 4, "float": 4,
    "int64_t": 8, "uint64_t": 8, "double": 8,
}


def x25(crc, data):
    for b in data:
        t = b ^ (crc & 0xFF)
        t = (t ^ (t << 4)) & 0xFF
        crc = ((crc >> 8) ^ (t << 8) ^ (t << 3) ^ (t >> 4)) & 0xFFFF
    return crc


def parse_type(t):
    """('uint8_t', 0) for 'uint8_t', ('char', 16) for 'char[16]'; '_mavlink_version' dropped."""
    t = t.strip()
    n = 0
    if "[" in t:
        base, rest = t.split("[", 1)
        n = int(rest.rstrip("]"))
        t = base
    if t == "uint8_t_mavlink_version":
        t = "uint8_t"
    if t not in SIZES:
        raise SystemExit(f"unknown field type {t}")
    return t, n


def messages_of(path, seen):
    path = path.resolve()
    if path in seen:
        return []
    seen.add(path)
    root = ET.parse(path).getroot()
    out = []
    for inc in root.findall("include"):
        out += messages_of(path.parent / inc.text.strip(), seen)
    msgs = root.find("messages")
    if msgs is None:
        return out
    for m in msgs.findall("message"):
        mid = int(m.get("id"))
        name = m.get("name")
        base, ext = [], []
        target = base
        for child in m:
            if child.tag == "extensions":
                target = ext
            elif child.tag == "field":
                t, n = parse_type(child.get("type"))
                target.append((t, child.get("name"), n))
        out.append((mid, name, base, ext, path.name))
    return out


def crc_extra(name, base):
    ordered = sorted(base, key=lambda f: -SIZES[f[0]])  # stable: keeps order within a size
    crc = x25(0xFFFF, (name + " ").encode())
    for t, fname, n in ordered:
        crc = x25(crc, (t + " ").encode())
        crc = x25(crc, (fname + " ").encode())
        if n:
            crc = x25(crc, bytes([n]))
    return (crc & 0xFF) ^ (crc >> 8)


def max_len(base, ext):
    return sum(SIZES[t] * (n or 1) for t, _, n in base + ext)


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    src = Path(sys.argv[1])
    out = Path(sys.argv[sys.argv.index("--out") + 1]) if "--out" in sys.argv else None
    commit = subprocess.run(["git", "-C", str(src), "rev-parse", "HEAD"], capture_output=True,
                            text=True, check=True).stdout.strip()
    msgs = messages_of(src / "message_definitions" / "v1.0" / "all.xml", set())
    table = {}
    for mid, name, base, ext, file in msgs:
        row = (crc_extra(name, base), max_len(base, ext), name)
        if mid in table and table[mid][:2] != row[:2]:
            raise SystemExit(f"message {mid} defined differently in two files ({table[mid][2]}, {name})")
        table.setdefault(mid, row)
    lines = [
        "// SPDX-License-Identifier: AGPL-3.0-only",
        "// @generated by scripts/gen_mavlink_table.py from the official MAVLink message definitions:",
        f"// github.com/mavlink/mavlink commit {commit}, message_definitions/v1.0/all.xml and its includes.",
        "// Do not edit by hand; run the script again. Only numbers derived from the definitions are",
        "// written here (message id, CRC_EXTRA, maximum payload length), with each message's name as a",
        "// comment; no definition text is copied.",
        "",
        "// PIN-SCOPE:    the mavlink/mavlink commit whose definitions this table was generated from",
        "// PIN-EXCLUDES: the table rows themselves (tests/mavlink_strict_crc.rs checks known values)",
        "/// The MAVLink definitions commit this table was generated from.",
        f'pub const DEFINITIONS_COMMIT: &str = "{commit}";',
        "",
        f"/// Every defined message, sorted by id: (message id, `CRC_EXTRA`, maximum payload length). {len(table)} messages.",
        "pub const MESSAGES: &[(u32, u8, u8)] = &[",
    ]
    for mid in sorted(table):
        ce, ml, name = table[mid]
        if ml > 255:
            raise SystemExit(f"{name}: payload {ml} > 255")
        lines.append(f"    ({mid}, {ce}, {ml}), // {name}")
    lines.append("];")
    text = "\n".join(lines) + "\n"
    if out:
        out.write_text(text)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
