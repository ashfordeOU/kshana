#!/usr/bin/env python3
"""Extract the GPS L1C code tables of IS-GPS-800J into the Rust block that
src/iq/signals/tables.rs carries, so the transcription is mechanical and reproducible.

Source: IS-GPS-800J, "NAVSTAR GPS Space Segment / User Segment L1C Interfaces",
01-AUG-2022, a US Government interface specification marked "DISTRIBUTION STATEMENT A.
Approved for public release. Distribution is unlimited."
  URL:     https://www.gps.gov/sites/default/files/2025-07/IS-GPS-800J.pdf
  SHA-256: c4aad71058a0eba1ba90672e9511566d2d124b49801cfaa42a51c21241815d0a
  Retrieved 2026-10-12. IRN-IS-800J-003 and IRN-IS-800J-004 (the later notices listed on
  gps.gov) change only sections 3.5 and 6.2.1/6.2.8.1 (navigation message), not the codes.

Tables read (PRNs 1-63):
  Table 3.2-2  L1C Ranging Codes Parameter Assignments: for L1CP and L1CD the Weil index w,
               the insertion index p, and the initial and final 24 chips (octal).
  Table 3.2-3  L1CO Overlay Code Parameter Assignments: the S1 polynomial coefficients,
               the initial 11 bits and the final 11 bits (octal, leading 0 dropped).
  Table 6.2-1  The length-10223 Legendre sequence (octal, 10224 bits, leading 0 ignored).

One transcription repair is applied and printed: the text layer of Table 3.2-2 sheet 2
renders PRN 38 as "3" (the row between PRN 37 and PRN 39); it is read as 38.

Usage:
  pdftotext -layout IS-GPS-800J.pdf IS-GPS-800J.txt
  python3 -I scripts/extract_is_gps_800_tables.py IS-GPS-800J.txt > block.rs
  python3 -I scripts/extract_is_gps_800_tables.py IS-GPS-800J.txt --check src/iq/signals/tables.rs

With --check the script exits non-zero unless the generated block appears verbatim in the
given file. Python standard library only.
"""
import re
import sys

RANGING_ROW = re.compile(
    r"^\s*(\d+)\s+(\d+)\s+(\d+)\s+([0-7]{8})\s+([0-7]{8})"
    r"\s+(\d+)\s+(\d+)\s+([0-7]{8})\s+([0-7]{8})\s*$"
)
OVERLAY_ROW = re.compile(r"^\s*(\d+)(?:\*+)?\s+([0-7]{4})\s+([0-7]{4})\s+([0-7]{4})\s*$")
OCTAL8 = re.compile(r"\b[0-7]{8}\b")


def is_heading(line, title):
    """A table heading in the body (not the list of tables, whose lines carry dot leaders)."""
    return title in line and "...." not in line


def section(lines, start_title, end_title):
    """Lines from the first body heading `start_title` up to the first body heading
    `end_title` after it."""
    out, inside = [], False
    for line in lines:
        if not inside and is_heading(line, start_title):
            inside = True
            continue
        if inside and is_heading(line, end_title):
            break
        if inside:
            out.append(line)
    if not inside:
        sys.exit(f"heading not found: {start_title!r}")
    return out


def ranging(lines):
    rows, prev = {}, None
    for line in section(lines, "Table 3.2-2. L1C Ranging Codes", "Table 3.2-3. L1CO Overlay"):
        m = RANGING_ROW.match(line)
        if not m:
            continue
        prn = int(m.group(1))
        if prev == 37 and prn == 3:
            print("// repair: Table 3.2-2 row printed as PRN 3 after PRN 37 read as PRN 38",
                  file=sys.stderr)
            prn = 38
        if prn in rows:
            sys.exit(f"Table 3.2-2: PRN {prn} twice")
        g = m.groups()
        rows[prn] = (
            (int(g[1]), int(g[2]), g[3], g[4]),
            (int(g[5]), int(g[6]), g[7], g[8]),
        )
        prev = prn
    if sorted(rows) != list(range(1, 64)):
        sys.exit(f"Table 3.2-2: expected PRNs 1-63, got {sorted(rows)}")
    return rows


def overlay(lines):
    rows = {}
    for line in section(lines, "Table 3.2-3. L1CO Overlay", "Figure 3.2-1. Generation"):
        m = OVERLAY_ROW.match(line)
        if not m:
            continue
        prn = int(m.group(1))
        if prn in rows:
            sys.exit(f"Table 3.2-3: PRN {prn} twice")
        rows[prn] = (m.group(2), m.group(3), m.group(4))
    if sorted(rows) != list(range(1, 64)):
        sys.exit(f"Table 3.2-3: expected PRNs 1-63, got {sorted(rows)}")
    return rows


def legendre(lines):
    body = []
    for line in section(lines, "Table 6.2-1. Legendre Sequence (Octal)", "Table 6.2-2."):
        if "NOTE" in line:
            break
        groups = OCTAL8.findall(line)
        if groups:
            body.append(groups)
    n = sum(len(g) for g in body)
    if n * 24 != 10224:
        sys.exit(f"Table 6.2-1: expected 426 octal groups (10224 bits), got {n}")
    return body


def emit(rng, ovl, leg):
    out = []
    w = out.append
    w("// --- GPS L1C (IS-GPS-800J) -----------------------------------------------------------")
    w("// BEGIN GENERATED by scripts/extract_is_gps_800_tables.py from IS-GPS-800J (01-AUG-2022),")
    w("// https://www.gps.gov/sites/default/files/2025-07/IS-GPS-800J.pdf, SHA-256")
    w("// c4aad71058a0eba1ba90672e9511566d2d124b49801cfaa42a51c21241815d0a, retrieved 2026-10-12;")
    w("// DISTRIBUTION STATEMENT A, approved for public release, distribution unlimited. Do not")
    w("// edit by hand. Table 3.2-2's text layer prints PRN 38 as \"3\"; the script reads it as 38.")
    w("")
    w("/// One component (L1CP or L1CD) of an IS-GPS-800J Table 3.2-2 row.")
    w("#[derive(Clone, Copy, Debug, PartialEq, Eq)]")
    w("pub struct L1cRow {")
    w("    /// Weil index `w` (shift of the Legendre sequence), 1..=5111.")
    w("    pub w: u16,")
    w("    /// Insertion index `p`: the expansion sequence is inserted before the `p`-th Weil")
    w("    /// chip (1-based), 1..=10223.")
    w("    pub p: u16,")
    w("    /// \"Initial 24 Chips (Octal)\" as printed, first chip in the most significant bit.")
    w("    pub first24: u32,")
    w("    /// \"Final 24 Chips (Octal)\" as printed, the earliest of them in the most significant")
    w("    /// bit.")
    w("    pub last24: u32,")
    w("}")
    w("")
    for name, idx, what in (("L1C_P", 0, "L1CP (pilot)"), ("L1C_D", 1, "L1CD (data)")):
        w(f"/// IS-GPS-800J (01-AUG-2022) Table 3.2-2, {what} columns: GPS PRN 1..=63, index `prn - 1`.")
        w(f"pub const {name}: [L1cRow; 63] = [")
        for prn in range(1, 64):
            ww, p, f24, l24 = rng[prn][idx]
            w("    L1cRow {")
            w(f"        w: {ww},")
            w(f"        p: {p},")
            w(f"        first24: 0o{f24},")
            w(f"        last24: 0o{l24},")
            w("    },")
        w("];")
        w("")
    w("/// One row of IS-GPS-800J Table 3.2-3 (L1CO overlay code, S1 generator), octal as printed.")
    w("#[derive(Clone, Copy, Debug, PartialEq, Eq)]")
    w("pub struct L1coRow {")
    w("    /// S1 polynomial coefficients `1, m10, ..., m1, 1` (bit `j` is the coefficient of")
    w("    /// `x^j`): octal 5111 is `1 + x^3 + x^6 + x^9 + x^11`.")
    w("    pub s1_poly: u16,")
    w("    /// Initial 11 bits (the initial register state `n11 ... n1`, `n11` in the most")
    w("    /// significant bit), which are also the first 11 output bits.")
    w("    pub initial: u16,")
    w("    /// Final 11 bits: the last 11 of the 1800 output bits, the earliest most significant.")
    w("    pub final11: u16,")
    w("}")
    w("")
    w("/// IS-GPS-800J (01-AUG-2022) Table 3.2-3: L1CO overlay codes, GPS PRN 1..=63, index `prn - 1`.")
    w("pub const L1C_O: [L1coRow; 63] = [")
    for prn in range(1, 64):
        poly, ini, fin = ovl[prn]
        w("    L1coRow {")
        w(f"        s1_poly: 0o{poly},")
        w(f"        initial: 0o{ini},")
        w(f"        final11: 0o{fin},")
        w("    },")
    w("];")
    w("")
    w("/// IS-GPS-800J (01-AUG-2022) Table 6.2-1: the length-10223 Legendre sequence as printed,")
    w("/// one string per printed row of 8-digit octal groups (10224 bits; the first bit is a")
    w("/// padding 0 the ICD says to ignore).")
    w(f"pub const L1C_LEGENDRE_OCTAL: [&str; {len(leg)}] = [")
    for groups in leg:
        w(f"    \"{''.join(groups)}\",")
    w("];")
    w("// END GENERATED")
    return "\n".join(out) + "\n"


def main():
    args = sys.argv[1:]
    if len(args) not in (1, 3) or (len(args) == 3 and args[1] != "--check"):
        sys.exit(__doc__)
    lines = open(args[0], encoding="utf-8").read().splitlines()
    block = emit(ranging(lines), overlay(lines), legendre(lines))
    if len(args) == 3:
        text = open(args[2], encoding="utf-8").read()
        if block not in text:
            sys.exit(f"{args[2]}: generated IS-GPS-800J block not found verbatim")
        print(f"{args[2]}: IS-GPS-800J block matches the extraction")
    else:
        sys.stdout.write(block)


if __name__ == "__main__":
    main()
