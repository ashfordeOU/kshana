// Data catalogues: the prose of the JSON files a page or the Studio shows (design v2, section 7 and the owner's "everything"). One message per
// distinct English string, id dat-<sha12>; the build writes a translated copy of each file under <lang>/ and the pages load it (lib/t.mjs fetchData).
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { createHash } from 'node:crypto';

export const sha12 = (s) => createHash('sha256').update(s).digest('hex').slice(0, 12);
export const dataId = (s) => 'dat-' + sha12(s);
const PROSE = /[A-Za-z]{3,}\s+[A-Za-z]{2,}/;
const NOT_PROSE = /^(https?:|[\w./-]+\.(json|svg|png|toml|md|rs|html|csv)$)/;

/** Read a spec file: JSON, or (module) `export default <JSON>;` with its leading comment lines kept as a header. */
export function readJsonFile(path, f) {
  const text = readFileSync(path, 'utf8');
  if (!f.module) return { json: JSON.parse(text), header: '' };
  const header = text.split('\n').filter((l) => /^\s*\/\//.test(l)).join('\n');
  const body = text.replace(/^\s*\/\/.*$/gm, '').trim().replace(/^export default /, '').replace(/;\s*$/, '');
  return { json: JSON.parse(body), header };
}
export function writeJsonFile(path, f, json, header) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, f.module ? `${header ? header + '\n' : ''}export default ${JSON.stringify(json)};\n` : JSON.stringify(json));
}

export const loadSpec = (root = 'i18n') => JSON.parse(readFileSync(join(root, 'data-spec.json'), 'utf8'));

/** Is this string a message? Prose of two words or more, on one line. */
export const isProse = (s) => typeof s === 'string' && PROSE.test(s) && !NOT_PROSE.test(s) && !s.includes('\n') && s.length <= 1200;

/** Walk a JSON value; call fn(string, setter) for every prose string that is not under a skipped key. */
export function walkProse(v, skip, fn, key = '') {
  if (Array.isArray(v)) v.forEach((x, i) => { if (typeof x === 'string') { if (isProse(x)) fn(x, (n) => { v[i] = n; }); } else walkProse(x, skip, fn, key); });
  else if (v && typeof v === 'object') {
    for (const k of Object.keys(v)) {
      if (skip.has(k)) continue;
      const x = v[k];
      if (typeof x === 'string') { if (isProse(x)) fn(x, (n) => { v[k] = n; }); } else walkProse(x, skip, fn, k);
    }
  }
}

const skipSet = (spec, f) => new Set([...(spec.skipKeys || []), ...(f.skipKeys || [])]);

/** Every distinct prose string of the spec's files under `src`: Map string -> {files:Set}. */
export function collectData(src, spec) {
  const out = new Map();
  for (const f of spec.files) {
    const p = join(src, f.file);
    if (!existsSync(p)) continue;
    const { json: j } = readJsonFile(p, f);
    walkProse(j, skipSet(spec, f), (s) => { if (!out.has(s)) out.set(s, new Set()); out.get(s).add(f.file); });
  }
  return out;
}

/** The English catalogue text. `fmt` turns a string into a message value (numbers and braces as literals, as for the pages). */
export function dataFtl(strings, fmt) {
  const lines = ['# Generated by tools/i18n.mjs data from the JSON files listed in i18n/data-spec.json. Do not edit.', '# Translators: copy to i18n/<lang>/data.ftl, translate the values, keep every id and every { "literal" } (numbers, versions, symbols).', ''];
  const ids = new Map();
  for (const [s, files] of [...strings].sort((a, b) => a[0].localeCompare(b[0]))) {
    const id = dataId(s);
    if (ids.has(id) && ids.get(id) !== s) throw new Error(`id collision for ${id}`);
    ids.set(id, s);
    lines.push(`# ${[...files].join(', ')}`, `${id} = ${fmt(s)}`, '');
  }
  return { text: lines.join('\n'), count: ids.size };
}

/** A translated copy of each spec file: `tr(string)` returns the translation or null (the English stays). Returns the number of strings replaced. */
export function applyData(src, out, spec, tr) {
  let replaced = 0, total = 0;
  for (const f of spec.files) {
    const p = join(src, f.file);
    if (!existsSync(p)) continue;
    const { json: j, header } = readJsonFile(p, f);
    walkProse(j, skipSet(spec, f), (s, set) => { total++; const t = tr(s); if (t !== null && t !== undefined) { set(t); replaced++; } });
    writeJsonFile(join(out, f.file), f, j, header);
  }
  return { replaced, total };
}
