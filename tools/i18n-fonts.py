#!/usr/bin/env python3
"""CJK font subsets for the ja and zh-Hans trees (design v2, section 10).

  python3 tools/i18n-fonts.py --tree site [--root i18n] [--cache DIR] [ja] [zh-Hans]

For each language: collect every character the language's catalogues (ui, glossary, pages, engine) use, plus ASCII and the usual
punctuation, subset Noto Sans JP or SC (weights 400 and 600) to exactly those characters as woff2, write
<tree>/fonts/noto-<lang>-<weight>-<hash>.woff2, and one <tree>/fonts/i18n-cjk.css with one @font-face per weight (a `unicode-range` of
the subset's own code points) and a :lang() rule that puts the subset after Geist. The OFL sources are fetched once with `npm pack`,
checked against tools/i18n-fonts.json and not committed. Needs fontTools and brotli (pip install fonttools brotli).
"""
import argparse, hashlib, json, os, re, subprocess, sys, tarfile, tempfile
from fontTools import subset
from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
BASE = [chr(c) for c in range(0x20, 0x7F)] + list("…–—‘’“”«»·•×−→←↑↓≤≥≈±°µ‰§©®™€")
CJK_PUNCT = list("、。，．・：；？！（）「」『』【】〔〕〈〉《》〜～—…")

def sha256(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()

def fetch(spec, cache):
    """Extract the package into the cache (npm pack, once) and return the directory holding package/."""
    d = os.path.join(cache, re.sub(r"[^\w.-]", "_", spec["package"]))
    if not os.path.isdir(os.path.join(d, "package")):
        os.makedirs(d, exist_ok=True)
        with tempfile.TemporaryDirectory() as t:
            out = subprocess.run(["npm", "pack", spec["package"], "--silent"], cwd=t, capture_output=True, text=True, check=True).stdout.strip().splitlines()[-1]
            with tarfile.open(os.path.join(t, out)) as tf:
                tf.extractall(d, filter="data")
    return d

def chars_of(root, lang):
    seen = set(BASE) | set(CJK_PUNCT)
    base = os.path.join(root, lang)
    for dp, _, fs in os.walk(base):
        for f in fs:
            if f.endswith(".ftl"):
                with open(os.path.join(dp, f), encoding="utf-8") as fh:
                    for ch in fh.read():
                        if ord(ch) > 0x7F: seen.add(ch)
    return seen

def ranges(codes):
    codes = sorted(codes)
    out, a, b = [], codes[0], codes[0]
    for c in codes[1:]:
        if c == b + 1: b = c
        else: out.append((a, b)); a = b = c
    out.append((a, b))
    return ", ".join("U+%X" % a if a == b else "U+%X-%X" % (a, b) for a, b in out)

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("langs", nargs="*", default=["ja", "zh-Hans"])
    ap.add_argument("--tree", required=True)
    ap.add_argument("--root", default="i18n")
    ap.add_argument("--cache", default=os.path.join(tempfile.gettempdir(), "i18n-fonts-cache"))
    a = ap.parse_args()
    src = json.load(open(os.path.join(HERE, "i18n-fonts.json")))
    fdir = os.path.join(a.tree, "fonts"); os.makedirs(fdir, exist_ok=True)
    css, total = [], 0
    for lang in a.langs:
        if lang not in src or not os.path.isdir(os.path.join(a.root, lang)): continue
        spec = src[lang]
        chars = chars_of(a.root, lang)
        pkg = fetch(spec, a.cache)
        fam = "Kshana %s" % ("JP" if lang == "ja" else "SC")
        for weight, info in spec["files"].items():
            ttf = os.path.join(pkg, info["path"])
            if sha256(ttf) != info["sha256"]: sys.exit("font source hash mismatch: " + ttf)
            font = TTFont(ttf)
            opts = subset.Options(); opts.flavor = "woff2"; opts.layout_features = ["*"]; opts.notdef_outline = True; opts.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
            sub = subset.Subsetter(opts); sub.populate(text="".join(sorted(chars))); sub.subset(font)
            cmap = sorted(c for c in font.getBestCmap() if c > 0x7F)
            name = "noto-%s-%s.woff2" % (lang, weight)
            tmp = os.path.join(fdir, name); font.flavor = "woff2"; font.save(tmp)
            h = sha256(tmp)[:8]; final = "noto-%s-%s-%s.woff2" % (lang, weight, h); os.replace(tmp, os.path.join(fdir, final))
            total += os.path.getsize(os.path.join(fdir, final))
            css.append('@font-face{font-family:"%s";font-style:normal;font-weight:%s;font-display:swap;src:url(%s) format("woff2");unicode-range:%s}' % (fam, weight, final, ranges(cmap)))
            print("%s %s: %d characters, %d KB" % (lang, weight, len(cmap), os.path.getsize(os.path.join(fdir, final)) // 1024))
        css.append(':lang(%s){--f-text:"Geist","%s",ui-sans-serif,system-ui,-apple-system,"Segoe UI",sans-serif;--f-display:"Bricolage Grotesque","%s",ui-sans-serif,system-ui,sans-serif}' % (lang, fam, fam))
    if css:
        open(os.path.join(fdir, "i18n-cjk.css"), "w").write("/* CJK subsets for the ja and zh-Hans pages: generated by tools/i18n-fonts.py, OFL fonts (Google Noto Sans JP and SC) */\n" + "\n".join(css) + "\n")
        print("fonts: %d KB in %s" % (total // 1024, fdir))

if __name__ == "__main__":
    main()
