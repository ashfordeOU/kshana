//! The `[clock_fit]` comparison pre-registered in tests/fixtures/clock_fit/PREREGISTRATION.md (and its
//! Addendum 1), committed before the generator, the code or any run existed.
//!
//! F1: the coefficients fitted from nine synthetic records of known noise (white FM, random-walk FM, both;
//! 131 072 samples at 1 s, written by `scripts/gen_clock_fit_ref.py`) agree with the truth. F2: the noise
//! exponent identified at every averaging factor equals allantools 2024.6 `noise_id` on the same record
//! (eleven records: the nine and two measured ones). F3: the run is wired as pre-registered and each
//! refusal names its cause. F4: the ensemble and single-run outputs carry the blocks they should.
//!
//! The synthetic records are seeded noise regenerated by the script into the git-ignored
//! `realdata-cache/clock_fit/` (override with `KSHANA_CLOCK_FIT_PATH`); the D2 record is the one the
//! readers' comparison writes into `realdata-cache/clock_log_real/`. When a record is absent its case prints a
//! skip notice and passes, unless `KSHANA_REQUIRE_REALDATA=1`; the vendored IGS record (D3), the wiring
//! and the refusals always run.
use serde_json::Value;
use std::f64::consts::{LN_2, PI};
use std::path::PathBuf;

const DIR: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/tests/fixtures/clock_fit");
const CUT: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/tests/fixtures/clock_log_real/igs_clk_30s_2026214_G01_ABMF.clk"
);

fn reference() -> Value {
    serde_json::from_str(&std::fs::read_to_string(format!("{DIR}/reference.json")).unwrap())
        .unwrap()
}

fn cache(var: &str, default: &str) -> PathBuf {
    std::env::var_os(var)
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(default))
}

fn base() -> String {
    std::fs::read_to_string(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/scenarios/clock-holdover.toml"
    ))
    .unwrap()
}

/// The clock scenario with a log table and a `[clock_fit]` table.
fn scenario(log: &str, replaces: &str) -> String {
    format!(
        "{}\n{log}\n[clock_fit]\nreplaces = \"{replaces}\"\n",
        base()
    )
}

fn log_timelab(path: &std::path::Path) -> String {
    format!(
        "[clock_log]\nformat = \"timelab\"\npath = \"{}\"\n",
        path.display()
    )
}

fn run(src: &str) -> Result<Value, String> {
    let out = kshana::api::run_toml(src).map_err(|e| e.to_string())?;
    Ok(serde_json::from_str(&out.json).unwrap())
}

/// Whether a cached record can run here; a missing one is a skip, or a failure when required.
fn present(path: &std::path::Path, what: &str) -> bool {
    if path.exists() {
        return true;
    }
    assert!(
        std::env::var("KSHANA_REQUIRE_REALDATA").as_deref() != Ok("1"),
        "{what}: {} is missing and KSHANA_REQUIRE_REALDATA=1 (run scripts/gen_clock_fit_ref.py)",
        path.display()
    );
    eprintln!(
        "SKIP {what}: {} not found (run scripts/gen_clock_fit_ref.py)",
        path.display()
    );
    false
}

fn finish(bar: &str, misses: Vec<String>) {
    assert!(
        misses.is_empty(),
        "{bar} not met in {} place(s):\n  {}",
        misses.len(),
        misses.join("\n  ")
    );
}

/// The card's noise Allan variance: white PM, white FM, flicker FM and random-walk FM, no drift.
fn noise_adev(f: &Value, tau: f64) -> f64 {
    let g = |k: &str| f[k].as_f64().unwrap();
    (3.0 * g("white_pm_var_s2") / (tau * tau)
        + 0.5 * g("h_0") / tau
        + 2.0 * LN_2 * g("h_m1")
        + (2.0 * PI * PI / 3.0) * g("h_m2") * tau)
        .sqrt()
}

fn truth_adev(h0: f64, hm2: f64, tau: f64) -> f64 {
    (h0 / (2.0 * tau) + (2.0 * PI * PI / 3.0) * hm2 * tau).sqrt()
}

fn synthetic_records() -> Vec<(String, f64, f64, PathBuf)> {
    let r = reference();
    let dir = cache("KSHANA_CLOCK_FIT_PATH", "realdata-cache/clock_fit");
    let mut v: Vec<_> = r["records"]
        .as_object()
        .unwrap()
        .iter()
        .filter(|(k, _)| k.starts_with("fit_C"))
        .map(|(k, rec)| {
            (
                k.clone(),
                rec["h0"].as_f64().unwrap(),
                rec["h_m2"].as_f64().unwrap(),
                dir.join(k),
            )
        })
        .collect();
    v.sort_by(|a, b| a.0.cmp(&b.0));
    v
}

#[test]
fn f1_known_coefficients_are_recovered() {
    let mut misses = Vec::new();
    let mut ran = 0;
    for (name, h0, hm2, path) in synthetic_records() {
        if !present(&path, &name) {
            continue;
        }
        ran += 1;
        let v = match run(&scenario(&log_timelab(&path), "classical")) {
            Ok(v) => v,
            Err(e) => {
                misses.push(format!("{name}: the run failed: {e}"));
                continue;
            }
        };
        let f = &v["fitted"];
        let g = |k: &str| f[k].as_f64().unwrap();
        eprintln!(
            "{name}: h_0 {:.3e} (true {h0:.3e}), h_-2 {:.3e} (true {hm2:.3e}), h_-1 {:.3e}, drift {:.2e} /s, {} fit points",
            g("h_0"),
            g("h_m2"),
            g("h_m1"),
            g("drift_per_s"),
            f["fit_points"].as_array().unwrap().len()
        );
        // (a) every coefficient present in the truth within a factor of 1.5, and the q values the run uses
        for (label, fit, truth, q_fit, q_true) in [
            ("h_0", g("h_0"), h0, g("q_wf"), 0.5 * h0),
            ("h_-2", g("h_m2"), hm2, g("q_rw"), 2.0 * PI * PI * hm2),
        ] {
            if truth == 0.0 {
                continue;
            }
            for (what, got, want) in [(label, fit, truth), ("its q", q_fit, q_true)] {
                let ratio = got / want;
                if !(ratio >= 1.0 / 1.5 && ratio <= 1.5) {
                    misses.push(format!(
                        "{name}: {what} fitted {got:e}, true {want:e} (ratio {ratio:.3})"
                    ));
                }
            }
        }
        // (b) the card's noise deviation within a factor of 1.35 of the true closed form at every fit point
        for p in f["fit_points"].as_array().unwrap() {
            let tau = p["tau_s"].as_f64().unwrap();
            let ratio = noise_adev(f, tau) / truth_adev(h0, hm2, tau);
            if !(ratio >= 1.0 / 1.35 && ratio <= 1.35) {
                misses.push(format!("{name}: card ADEV / truth at {tau} s = {ratio:.3}"));
            }
        }
    }
    if ran > 0 {
        assert_eq!(ran, 9, "all nine synthetic records or none");
    }
    finish("F1", misses);
}

/// The identified exponent at each fit point of a `fitted` block against the reference's.
fn alpha_parity(name: &str, f: &Value, rec: &Value, tau0: f64, misses: &mut Vec<String>) -> f64 {
    let alphas: Vec<(f64, Option<i64>)> = rec["alphas"]
        .as_array()
        .unwrap()
        .iter()
        .map(|p| (p[0].as_f64().unwrap() * tau0, p[1].as_i64()))
        .collect();
    let (mut compared, mut equal) = (0usize, 0usize);
    for p in f["fit_points"].as_array().unwrap() {
        let tau = p["tau_s"].as_f64().unwrap();
        let Some(mine) = p["alpha"].as_i64() else {
            continue; // the fallback (random-walk FM) applied: nothing identified to compare
        };
        let Some((_, Some(theirs))) = alphas.iter().find(|(t, _)| (t - tau).abs() <= 1e-9 * tau)
        else {
            continue;
        };
        compared += 1;
        if mine == *theirs {
            equal += 1;
        }
    }
    let frac = if compared == 0 {
        0.0
    } else {
        equal as f64 / compared as f64
    };
    eprintln!("{name}: noise exponent equal at {equal} of {compared} fit points");
    if compared < 3 || frac < 0.9 {
        misses.push(format!(
            "{name}: exponent equal at {equal} of {compared} points ({frac:.2})"
        ));
    }
    frac
}

#[test]
fn f2_noise_identification_agrees_with_allantools() {
    let r = reference();
    let mut misses = Vec::new();
    for (name, _, _, path) in synthetic_records() {
        if !present(&path, &name) {
            continue;
        }
        match run(&scenario(&log_timelab(&path), "classical")) {
            Ok(v) => {
                alpha_parity(&name, &v["fitted"], &r["records"][&name], 1.0, &mut misses);
            }
            Err(e) => misses.push(format!("{name}: the run failed: {e}")),
        }
    }
    let d2 = cache(
        "KSHANA_CLOCK_LOG_REAL_PATH",
        "realdata-cache/clock_log_real",
    )
    .join("d2_TL-P.txt");
    if present(&d2, "D2") {
        match run(&scenario(&log_timelab(&d2), "classical")) {
            Ok(v) => {
                alpha_parity("D2", &v["fitted"], &r["records"]["D2"], 1.0, &mut misses);
            }
            Err(e) => misses.push(format!("D2: the run failed: {e}")),
        }
    }
    let d3 = format!("[clock_log]\nformat = \"rinex-clk\"\npath = \"{CUT}\"\nclock = \"G01\"\n");
    match run(&scenario(&d3, "classical")) {
        Ok(v) => {
            alpha_parity("D3", &v["fitted"], &r["records"]["D3"], 30.0, &mut misses);
        }
        Err(e) => misses.push(format!("D3: the run failed: {e}")),
    }
    finish("F2", misses);
}

// ---- F3: wiring and refusals --------------------------------------------------------------

const D3: &str = "[clock_log]\nformat = \"rinex-clk\"\npath = \"{CUT}\"\nclock = \"G01\"\n";

fn d3_log() -> String {
    D3.replace("{CUT}", CUT)
}

#[test]
fn f3_the_fit_is_wired_as_registered() {
    for replaces in ["classical", "quantum"] {
        let v = run(&scenario(&d3_log(), replaces)).unwrap();
        let f = &v["fitted"];
        // The same scenario with the clock's values written literally.
        let g = |k: &str| f[k].as_f64().unwrap();
        let other = if replaces == "classical" {
            "quantum"
        } else {
            "classical"
        };
        let mut scn: toml::Table = base().parse().unwrap();
        let t = scn[&format!("clock_{replaces}")].as_table_mut().unwrap();
        t.insert("id".into(), f["clock_id"].as_str().unwrap().into());
        t.insert("q_wf".into(), g("q_wf").into());
        t.insert("q_rw".into(), g("q_rw").into());
        t.insert("drift".into(), g("drift").into());
        t.insert("flicker_floor".into(), g("flicker_floor").into());
        let literal = run(&toml::to_string(&scn).unwrap()).unwrap();
        for side in [replaces, other] {
            assert_eq!(
                v[side]["fom"], literal[side]["fom"],
                "{replaces}: {side} fom"
            );
        }
        // y0 is kept; the clock carries the measured id.
        assert_eq!(v[replaces]["spec"]["id"], f["clock_id"]);
        assert_eq!(
            v[replaces]["spec"]["params"]["y0"].as_f64(),
            Some(g("y0_kept"))
        );
        assert_eq!(f["not_simulated"][0], "white phase noise");
        assert!(f["label"].as_str().unwrap().starts_with("MODELLED"));
    }
    // A scenario without [clock_fit] has no fitted block and runs as before.
    let plain = run(&format!("{}\n{}", base(), d3_log())).unwrap();
    assert!(plain.get("fitted").is_none());
    assert!(plain["measured"].is_object());
}

#[test]
fn f3_each_refusal_names_its_cause() {
    let log = d3_log();
    // [clock_fit] without [clock_log]
    let e = run(&format!(
        "{}\n[clock_fit]\nreplaces = \"classical\"\n",
        base()
    ))
    .unwrap_err();
    assert!(e.contains("[clock_log]"), "{e}");
    // replaces neither quantum nor classical
    let e = run(&scenario(&log, "both")).unwrap_err();
    assert!(e.contains("replaces") && e.contains("\"both\""), "{e}");
    // no frequency noise: a perfectly linear phase ramp (conditioning removes the quadratic)
    let ramp: String = (0..400)
        .map(|k| format!("{:e}\n", k as f64 * 1e-9))
        .collect();
    let flat =
        format!("[clock_log]\nformat = \"timelab\"\ntext = \"\"\"\n# tau0 = 1\n{ramp}\"\"\"\n");
    let e = run(&scenario(&flat, "classical")).unwrap_err();
    assert!(
        e.contains("no frequency noise") || e.contains("[clock_fit]"),
        "{e}"
    );
    // a log too short to fit
    let short = "[clock_log]\nformat = \"timelab\"\ntext = \"\"\"\n# tau0 = 1\n0\n1e-9\n3e-9\n6e-9\n\"\"\"\n";
    let e = run(&scenario(short, "classical")).unwrap_err();
    assert!(e.contains("[clock_fit]"), "{e}");
}

#[test]
fn f4_ensemble_and_single_run_carry_their_blocks() {
    let single = run(&scenario(&d3_log(), "classical")).unwrap();
    assert!(single["fitted"].is_object() && single["measured"].is_object());
    let many = format!("runs = 20\n{}", scenario(&d3_log(), "classical"));
    let v = run(&many).unwrap();
    assert!(
        v["fitted"].is_object(),
        "the ensemble run has the fitted block"
    );
    assert!(v.get("measured").is_none(), "and no measured block");
    assert!(v["units"]["fitted.q_wf"].is_object());
}
