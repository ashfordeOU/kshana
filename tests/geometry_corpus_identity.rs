/// The corpora are scored past calibration, so the identity is not an empty one.
#[test]
fn the_corpora_are_scored() {
    for (name, bytes) in corpora() {
        let (_, scn) = session_for(&name, &bytes);
        let r = run_receiver_trust(&scn).unwrap();
        let scored = r.epochs.iter().filter(|e| e.score.is_some()).count();
        assert!(scored >= 50, "{name}: {scored} scored epochs");
        // The geometry deduction is not a [score] weight: score_model.weights is as in 0.35
        // (the identity strips every `geometry` key, so it is checked here, unstripped).
        let v = serde_json::to_value(&r).unwrap();
        let weights = v["score_model"]["weights"].as_object().unwrap();
        assert!(!weights.contains_key("geometry"), "{name}");
        assert_eq!(weights.len(), 16, "{name}");
        // The geometry monitor decided, so it is listed, last.
        assert_eq!(
            v["monitors_run"].as_array().unwrap().last(),
            Some(&Value::String("geometry".into())),
            "{name}"
        );
    }
}

/// The two crew-training scenarios whose events make the geometry poor (a jamming loss of
/// most satellites), with the times of their poor epochs as 0.36 labels them
/// (`tests/fixtures/geometry_identity/poor_epochs.json`; the 0.36 test checks the list against
/// the labels, so it cannot drift).
const WITH_POOR: [&str; 2] = ["combined-event", "open-sea-jamming"];

fn poor_epochs() -> std::collections::BTreeMap<String, Vec<f64>> {
    serde_json::from_str(
        &std::fs::read_to_string(
            Path::new(ROOT).join("tests/fixtures/geometry_identity/poor_epochs.json"),
        )
        .unwrap(),
    )
    .unwrap()
}

fn round_1dp(x: f64) -> f64 {
    (x.clamp(0.0, 100.0) * 10.0).round() / 10.0
}

/// `(sha of the epochs that are not poor, sha of the poor ones without the geometry
/// deduction)`, both in the 0.35 view, each the whole epoch. A poor epoch's score and band are recomputed from its
/// other deductions (`round_1dp(clamp(100 - sum))`, bands at 90 and 55): for 0.35, which has
/// no geometry deduction, that is checked to be the score it wrote.
fn split_hashes(r: &Value, poor: &[f64]) -> (String, String) {
    let mut keep = String::new();
    let mut without = String::new();
    for e in r["epochs"].as_array().unwrap() {
        let t = e["t_s"].as_f64().unwrap();
        if !poor.contains(&t) {
            keep.push_str(&serde_json::to_string(e).unwrap());
            keep.push('\n');
            continue;
        }
        let sc = &e["score"];
        let all: Vec<&Value> = sc["deductions"].as_array().unwrap().iter().collect();
        let others: Vec<Value> = all
            .iter()
            .filter(|d| d["monitor"] != "geometry")
            .map(|d| (*d).clone())
            .collect();
        let sum = |ds: &mut dyn Iterator<Item = &Value>| -> f64 {
            ds.map(|d| d["points"].as_f64().unwrap()).sum()
        };
        let score = round_1dp(100.0 - sum(&mut others.iter()));
        assert_eq!(
            sc["score"].as_f64().unwrap(),
            round_1dp(100.0 - sum(&mut all.iter().copied())),
            "t {t}"
        );
        if all.len() == others.len() {
            assert_eq!(sc["score"].as_f64().unwrap(), score, "t {t}");
        }
        let band = if score >= 90.0 {
            "nominal"
        } else if score >= 55.0 {
            "degraded"
        } else {
            "untrusted"
        };
        // The whole epoch, with only the score, its band, the state and the geometry deduction
        // replaced.
        let mut view = e.clone();
        view["state"] = Value::String(band.into());
        view["score"]["score"] = serde_json::json!(score);
        view["score"]["band"] = Value::String(band.into());
        view["score"]["deductions"] = Value::Array(others);
        without.push_str(&serde_json::to_string(&view).unwrap());
        without.push('\n');
    }
    (sha(&keep), sha(&without))
}

fn training_result(name: &str) -> Value {
    let text =
        std::fs::read_to_string(Path::new(ROOT).join(format!("scenarios/training/{name}.toml")))
            .unwrap();
    let nmea = generate(&TrainingScenario::parse(&text).unwrap())
        .unwrap()
        .nmea_text();
    let (_, scn) = session_for(name, nmea.as_bytes());
    let r = run_receiver_trust(&scn).unwrap();
    let mut v = serde_json::to_value(&r).unwrap();
    strip(&mut v);
    v
}

#[test]
fn poor_epochs_differ_from_0_36_portable_by_the_geometry_deduction_alone() {
    // PIN-SCOPE:    every batch epoch of the two training scenarios with poor geometry: the
    //               epochs that are not poor as written, the poor ones whole with only the
    //               geometry deduction removed and the score, band and state recomputed
    // PIN-EXCLUDES: the keys in APPENDED, schema string, scenario_hash, key order; the geometry
    //               deduction of a poor epoch, the one intended change
    let poor = poor_epochs();
    let mut got = Vec::new();
    for name in WITH_POOR {
        let r = training_result(name);
        let ts = &poor[name];
        // The fixture is the 0.36 labels, read back from the run (absent in 0.35).
        if r["epochs"][0].get("geometry").is_none() {
            eprintln!("0.35 run: no labels to check the fixture against");
        }
        let (keep, without) = split_hashes(&r, ts);
        eprintln!("(\"{name}\", \"{keep}\", \"{without}\"),");
        got.push((name, keep, without));
    }
    for (name, keep, without) in got {
        let pin = SPLIT_PINS.iter().find(|p| p.0 == name).unwrap();
        assert_eq!((keep.as_str(), without.as_str()), (pin.1, pin.2), "{name}");
    }
}

#[test]
fn the_poor_epoch_fixture_is_the_0_36_labels_and_only_poor_epochs_deduct() {
    for name in TRAINING {
        let text = std::fs::read_to_string(
            Path::new(ROOT).join(format!("scenarios/training/{name}.toml")),
        )
        .unwrap();
        let nmea = generate(&TrainingScenario::parse(&text).unwrap())
            .unwrap()
            .nmea_text();
        let (_, scn) = session_for(name, nmea.as_bytes());
        let r = serde_json::to_value(run_receiver_trust(&scn).unwrap()).unwrap();
        let mut labelled = Vec::new();
        for e in r["epochs"].as_array().unwrap() {
            let poor = e["geometry"]["label"] == "poor";
            if poor {
                labelled.push(e["t_s"].as_f64().unwrap());
            }
            let geo = e["score"]["deductions"]
                .as_array()
                .into_iter()
                .flatten()
                .any(|d| d["monitor"] == "geometry");
            assert!(
                !geo || poor,
                "{name} t {}: a geometry deduction that is not poor",
                e["t_s"]
            );
        }
        let want = poor_epochs().get(name).cloned().unwrap_or_default();
        assert_eq!(labelled, want, "{name}");
    }
}

