//! The geometry monitor deducts only when the geometry is poor (HDOP above 4, PDOP above 6 or
//! fewer than 5 satellites used); good and fair geometry score exactly as in engine 0.35.0. This
//! file proves it on every committed vessel NMEA corpus long enough to be scored: the maritime
//! demo and the maritime reference fixtures, each also as GPS-only open sky (the Galileo GSV
//! removed: 8 satellites, fair geometry, where a ramp from half the threshold cost 1.875 points
//! an epoch), and on the four crew-training scenarios generated from their seeds. Each log is scored with the demo's vessel session (calibrating on
//! the first 30 s of the short logs), as a batch run and as a replayed live stream; with the keys
//! 0.36 appends removed, every output is byte-identical to what 0.35.0 wrote.
//!
//! The pins were taken by running this file on the 0.35.0 release commit (35c1558d), checked
//! out at a different path, where the removal is a no-op. The scoring was checked to be
//! non-trivial there: see `the_corpora_are_scored`. The scenario hash covers the resolved
//! (absolute) log path, so it is replaced by a placeholder: the pins hold for any checkout.

