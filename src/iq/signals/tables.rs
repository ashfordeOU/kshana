//! Code-assignment tables transcribed from the interface control documents.
//!
//! Each table carries the parameters a generator needs **and** an independent column the
//! same ICD prints for checking (an end state, an initial-state vector or the first chips),
//! so the tests can confirm the generator against the ICD rather than against itself.
//! The rows were extracted mechanically from the ICD text (`pdftotext -layout`) and are
//! not edited by hand; the ICD issue of each table is stated on it.
//!
//! The GPS L1C tables at the end (IS-GPS-800J Tables 3.2-2, 3.2-3 and 6.2-1) are written
//! by `scripts/extract_is_gps_800_tables.py`, which also checks (`--check`) that the block
//! here is byte-identical to what it extracts; the source URL, PDF SHA-256, retrieval date
//! and distribution statement are in the block's header comment.
//!
//! PIN-SCOPE:    no hash or byte pin: the long digit strings are the ICD's printed octal
//!               Legendre sequence (IS-GPS-800J Table 6.2-1), data the generator reads, checked
//!               against the ICD text by the extraction script's `--check`.
//! PIN-EXCLUDES: nothing; the tables are transcribed data, not fingerprints of an output.

