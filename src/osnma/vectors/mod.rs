//! Open, versioned OSNMA vector set made from Kshana's own synthetic data, and its runner
//! (`kshana osnma vectors`; format in `docs/OSNMA-VECTORS.md`).
//!
//! A set is a directory: `manifest.json` (the vectors, the SHA-256 of every input, the verifier
//! arguments of each), `bars.json` (one fixed pass bar per vector) and `inputs/` (plain page
//! files that `kshana osnma verify` reads directly). The bars are written before any run and
//! hashed: the manifest names the hash, the runner refuses a bar file whose hash differs, and
//! for the built-in set the hash is also pinned in this source ([`BARS_SHA256_V1`]). There is
//! one fixed bar per vector, nothing adapts to earlier results, and results are reported per
//! run, never pooled.
//!
//! The data is synthetic and comes from our own reading of the SIS ICD Issue 1.1 and the
//! Receiver Guidelines Issue 1.3 (© European Union; cited by section, not copied). Passing the
//! set shows consistency with that reading, not conformance to the Galileo system, and it is
//! not a certification of any kind. The official test vectors stay outside this repository
//! (download on demand, SHA-256 pinned: `tests/osnma_official_vectors.rs`).

pub mod gen;
pub mod set_v1;

use super::cli::{parse_public_key, verify_report, VerifyParams};
