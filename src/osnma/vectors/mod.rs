use std::path::Path;

/// Format id of a set manifest.
pub const MANIFEST_FORMAT: &str = "kshana-osnma-vectors/1";
/// Format id of a bar file.
pub const BARS_FORMAT: &str = "kshana-osnma-bars/1";
/// Format id of a run result.
pub const RESULT_FORMAT: &str = "kshana-osnma-vectors-result/1";
/// Name of the built-in set.
pub const SET_NAME: &str = "kshana-osnma-synthetic";
/// Version of the built-in set.
pub const SET_VERSION: &str = "1.0.0";
// PIN-SCOPE:    the bar file (bars.json) of the built-in synthetic set, version 1.0.0, byte for byte
// PIN-EXCLUDES: nothing; the manifest and the input files carry their own hashes
/// SHA-256 of the bar file of the built-in set, version 1.0.0. A change of any bar changes
/// this value, which must then be changed here together with the set version.
pub const BARS_SHA256_V1: &str = "cbf7ac5d4207c32117c85a82050a59055e20e367563c12e45e7d6bb028ab5b87";

/// What every result says about its own scope.
pub const SCOPE: &str = "Synthetic vectors generated by Kshana from its own reading of the Galileo OSNMA SIS ICD Issue 1.1 and Receiver Guidelines Issue 1.3 (source acknowledged; (c) European Union). A pass shows consistency with that reading, not conformance to the Galileo system; this is not a certification and implies no approval or endorsement by the European Union, EUSPA or any other body.";

fn sha256_hex(b: &[u8]) -> String {
    hex::encode(Sha256::digest(b))
}

fn key_arg(k: &PublicKey) -> String {
    let ty = match k.key_type {
        KeyType::P256 => "p256",
        KeyType::P521 => "p521",
    };
    format!("{}:{ty}:{}", k.pkid, hex::encode(&k.bytes))
}

/// One generated vector: its manifest entry and its input file.
pub struct Generated {
    /// The vector's manifest entry (id, category, input path, references, bars).
    pub entry: Value,
    /// The vector's input file text (I/NAV pages in the plain format).
    pub input: String,
}

/// The built-in set: (manifest, bars file text, generated vectors). Deterministic.
pub fn generate() -> (Value, String, Vec<Generated>) {
    let defs = set_v1::vectors();
    let mut bars = serde_json::Map::new();
    let mut out = Vec::new();
    for d in &defs {
        let b = (d.build)();
        let input = gen::render_pages(d.id, &b.pages);
        let path = format!("inputs/{}.txt", d.id);
        let keys: Vec<String> = b.public_keys.iter().map(key_arg).collect();
        let mut cmd = format!("kshana osnma verify {path}");
        if let Some(r) = b.merkle_root {
            cmd.push_str(&format!(" --merkle-root {}", hex::encode(r)));
        }
        for k in &keys {
            cmd.push_str(&format!(" --public-key {k}"));
        }
        if let Some(t) = b.reference_time {
            cmd.push_str(&format!(" --reference-time {t}"));
        }
        if let Some(e) = b.max_time_error {
            cmd.push_str(&format!(" --max-time-error {e}"));
        }
        cmd.push_str(" --json");
        let entry = json!({
            "id": d.id,
            "category": d.category,
            "title": d.title,
            "refs": d.refs,
            "input": path,
            "input_sha256": sha256_hex(input.as_bytes()),
            "pages": b.pages.len(),
            "verify": {
                "merkle_root": b.merkle_root.map(hex::encode),
                "public_keys": keys,
                "reference_time": b.reference_time,
                "max_time_error": b.max_time_error,
            },
            "command": cmd,
        });
        bars.insert(d.id.to_string(), (d.bars)());
        out.push(Generated { entry, input });
    }
    let bars_text = to_text(&json!({
        "format": BARS_FORMAT,
        "set": SET_NAME,
        "set_version": SET_VERSION,
        "bars": bars,
    }));
    let manifest = json!({
        "format": MANIFEST_FORMAT,
        "set": SET_NAME,
        "set_version": SET_VERSION,
        "sources": {
            "icd": "Galileo OSNMA Signal-in-Space ICD, Issue 1.1, October 2023",
            "receiver_guidelines": "Galileo OSNMA Receiver Guidelines, Issue 1.3, January 2024",
            "acknowledgement": "Section numbers are citations of documents (c) European Union, published by the European GNSS Service Centre; no text, table or vector of them is reproduced. Use of the ICD technical data relies on its Annex E authorisation (docs/OSNMA.md, NOTICE).",
        },
        "scope": SCOPE,
        "generator": "kshana osnma vectors generate",
        "licence": "AGPL-3.0-only (Kshana's own synthetic data)",
        "bars_file": "bars.json",
        "bars_sha256": sha256_hex(bars_text.as_bytes()),
        "vectors": out.iter().map(|g| g.entry.clone()).collect::<Vec<_>>(),
    });
    (manifest, bars_text, out)
}

/// Pretty JSON with a final newline: the byte form that is hashed.
pub fn to_text(v: &Value) -> String {
    let mut s = serde_json::to_string_pretty(v).unwrap_or_default();
    s.push('\n');
    s
}

/// Write the built-in set to `dir` (manifest, bars, inputs).
pub fn write_set(dir: &Path) -> std::io::Result<usize> {
    let (manifest, bars, gens) = generate();
    std::fs::create_dir_all(dir.join("inputs"))?;
    std::fs::write(dir.join("manifest.json"), to_text(&manifest))?;
    std::fs::write(dir.join("bars.json"), bars)?;
    for g in &gens {
        let p = g.entry["input"].as_str().unwrap_or_default();
        std::fs::write(dir.join(p), &g.input)?;
    }
    Ok(gens.len())
}

// ------------------------------------------------------------------------ the bar check ---

/// One bar line and whether it held.
fn check(name: &str, expected: Value, observed: Value, pass: bool) -> Value {
    json!({"bar": name, "expected": expected, "observed": observed, "pass": pass})
}

/// Whether an event of the report matches a matcher: every field of the matcher equals the
/// event's (a string field also matches an event value that starts with it and `(`).
fn event_matches(m: &Value, e: &Value) -> bool {
    let Some(mo) = m.as_object() else {
        return false;
    };
    mo.iter().all(|(k, want)| match (want, e.get(k)) {
        (Value::String(w), Some(Value::String(got))) => {
            got == w || got.starts_with(&format!("{w}("))
        }
        (w, Some(got)) => w == got,
        (_, None) => false,
    })
}

fn event_count(report: &Value, m: &Value) -> u64 {
    report["events"]
        .as_array()
        .map(|es| {
            es.iter()
                .filter(|e| event_matches(m, e))
                .map(|e| e["count"].as_u64().unwrap_or(1))
                .sum()
        })
        .unwrap_or(0)
}

fn tag_state_count(report: &Value, state: &str) -> u64 {
    report["tags"]
        .as_array()
        .map(|ts| {
            ts.iter()
                .filter(|t| t["status"]["state"].as_str() == Some(state))
                .count() as u64
        })
        .unwrap_or(0)
}

fn sat_status(report: &Value, sat: &str) -> Value {
    report["satellites"]
        .as_array()
        .and_then(|ss| ss.iter().find(|s| s["sat"].as_str() == Some(sat)))
        .map(|s| s["status"].clone())
        .unwrap_or(Value::Null)
}

fn has_reason(report: &Value, state: &str, reason: &str) -> bool {
    report["tags"].as_array().is_some_and(|ts| {
        ts.iter().any(|t| {
            t["status"]["state"].as_str() == Some(state)
                && t["status"]["reason"].as_str() == Some(reason)
        })
    })
}

/// Evaluate one bar against a `kshana osnma verify --json` report and its exit status.
/// Returns every bar line; the vector passes when all hold. An unknown bar key fails, so a
/// bar file cannot ask for something the runner silently ignores.
pub fn evaluate(bar: &Value, report: &Value, exit: i32) -> Vec<Value> {
    let mut out = Vec::new();
    let Some(obj) = bar.as_object() else {
        out.push(check("bar", json!("an object"), bar.clone(), false));
        return out;
    };
    for (key, want) in obj {
        match key.as_str() {
            "overall" | "alert" | "nma_status" | "freshness_enforced" => {
                let got = report[key.as_str()].clone();
                let pass = &got == want;
                out.push(check(key, want.clone(), got, pass));
            }
            "exit" => {
                let pass = want.as_i64() == Some(i64::from(exit));
                out.push(check(key, want.clone(), json!(exit), pass));
            }
            "satellites" | "satellites_not" => {
                for (sat, st) in want.as_object().into_iter().flatten() {
                    let got = sat_status(report, sat);
                    let pass = if key == "satellites" {
                        &got == st
                    } else {
                        // A satellite the report does not list has no status at all, which is
                        // not the status named.
                        &got != st
                    };
                    out.push(check(&format!("{key}.{sat}"), st.clone(), got, pass));
                }
            }
            "tags" => {
                for (k, n) in want.as_object().into_iter().flatten() {
                    let (state, is_min) = match k.as_str() {
                        "authenticated_min" => ("authenticated", true),
                        "authenticated_max" => ("authenticated", false),
                        "failed_min" => ("failed", true),
                        "failed_max" => ("failed", false),
                        _ => {
                            out.push(check(&format!("tags.{k}"), n.clone(), Value::Null, false));
                            continue;
                        }
                    };
                    let got = tag_state_count(report, state);
                    let lim = n.as_u64().unwrap_or(u64::MAX);
                    let pass = if is_min { got >= lim } else { got <= lim };
                    out.push(check(&format!("tags.{k}"), n.clone(), json!(got), pass));
                }
            }
            "adkd_authenticated" => {
                for a in want.as_array().into_iter().flatten() {
                    let got = report["tags"]
                        .as_array()
                        .map(|ts| {
                            ts.iter()
                                .filter(|t| {
                                    &t["adkd"] == a
                                        && t["status"]["state"].as_str() == Some("authenticated")
                                })
                                .count()
                        })
                        .unwrap_or(0);
                    out.push(check(
                        &format!("adkd_authenticated.{a}"),
                        json!(">= 1"),
                        json!(got),
                        got >= 1,
                    ));
                }
            }
            "fail_reasons" | "pending_reasons" => {
                let state = if key == "fail_reasons" {
                    "failed"
                } else {
                    "pending"
                };
                for r in want.as_array().into_iter().flatten() {
                    let rs = r.as_str().unwrap_or_default();
                    let pass = has_reason(report, state, rs);
                    out.push(check(
                        &format!("{key}.{rs}"),
                        json!("present"),
                        json!(if pass { "present" } else { "absent" }),
                        pass,
                    ));
                }
            }
            "events_present" | "events_absent" => {
                for m in want.as_array().into_iter().flatten() {
                    let n = event_count(report, m);
                    let pass = if key == "events_present" {
                        n >= 1
                    } else {
                        n == 0
                    };
                    out.push(check(key, m.clone(), json!(n), pass));
                }
            }
            "event_counts" => {
                for c in want.as_array().into_iter().flatten() {
                    let n = event_count(report, &c["match"]);
                    let min = c["min"].as_u64().unwrap_or(0);
                    let max = c["max"].as_u64().unwrap_or(u64::MAX);
                    out.push(check(
                        "event_counts",
                        c.clone(),
                        json!(n),
                        n >= min && n <= max,
                    ));
                }
            }
            other => out.push(check(other, want.clone(), json!("unknown bar"), false)),
        }
    }
    out
}

