/// `kshana osnma vectors <generate|run> ...`; returns the process exit code: 0 every vector
/// met its bar, 1 at least one did not, 2 a usage, input or set-integrity error.
pub fn run_cli(args: &[String]) -> i32 {
    let advisory = crate::legal::text("legal-osnma-advisory");
    let usage = || crate::t!("osnma-vectors-usage");
    match args.first().map(String::as_str) {
        Some("generate") => {
            let mut out = None;
            let mut it = args[1..].iter();
            while let Some(a) = it.next() {
                match a.as_str() {
                    "--out" => out = it.next().cloned(),
                    s => {
                        eprintln!(
                            "{advisory}\n\n{}\n\n{}",
                            crate::terr!("e-iq-io-cli-unknown-option", s = s),
                            usage()
                        );
                        return 2;
                    }
                }
            }
            let Some(out) = out else {
                eprintln!("{advisory}\n\n{}", usage());
                return 2;
            };
            match write_set(Path::new(&out)) {
                Ok(n) => {
                    println!("{}", crate::t!("osnma-vectors-written", n = n, dir = out));
                    0
                }
                Err(e) => {
                    eprintln!("{advisory}\n\n{}", crate::t!("main-fail", e = e));
                    2
                }
            }
        }
        Some("run") => {
            let (mut dir, mut json_out, mut only) = (None, false, Vec::new());
            let mut it = args[1..].iter();
            while let Some(a) = it.next() {
                match a.as_str() {
                    "--json" => json_out = true,
                    "--only" => only.extend(it.next().cloned()),
                    s if s.starts_with("--") => {
                        eprintln!(
                            "{advisory}\n\n{}\n\n{}",
                            crate::terr!("e-iq-io-cli-unknown-option", s = s),
                            usage()
                        );
                        return 2;
                    }
                    s if dir.is_none() => dir = Some(s.to_string()),
                    s => {
                        eprintln!(
                            "{advisory}\n\n{}",
                            crate::terr!("e-nmea-synth-cli-unexpected-argument", s = s)
                        );
                        return 2;
                    }
                }
            }
            let set = match &dir {
                Some(d) => match LoadedSet::from_dir(Path::new(d)) {
                    Ok(s) => s,
                    Err(e) => {
                        eprintln!("{advisory}\n\n{}", crate::t!("main-fail", e = e));
                        return 2;
                    }
                },
                None => LoadedSet::builtin(),
            };
            let result = match crate::i18n::in_english_or_localised_error(|| run_set(&set, &only)) {
                Ok(r) => r,
                Err(e) => {
                    eprintln!("{advisory}\n\n{}", crate::t!("main-fail", e = e));
                    return 2;
                }
            };
            if json_out {
                println!("{}", to_text(&result).trim_end());
            } else {
                print_table(&result, &advisory);
            }
            if result["failed"].as_u64() == Some(0) && result["total"].as_u64() != Some(0) {
                0
            } else {
                1
            }
        }
        Some("--help" | "-h") => {
            println!("{advisory}\n\n{}", usage());
            0
        }
        _ => {
            eprintln!("{advisory}\n\n{}", usage());
            2
        }
    }
}

fn print_table(r: &Value, advisory: &str) {
    println!("{advisory}\n");
    println!(
        "{}",
        crate::t!(
            "osnma-vectors-header",
            set = r["set"].as_str().unwrap_or("?"),
            version = r["set_version"].as_str().unwrap_or("?"),
            bars = r["bars_sha256"].as_str().unwrap_or("?")
        )
    );
    println!("{}\n", crate::t!("osnma-vectors-scope"));
    println!("{}", crate::t!("osnma-vectors-table-head"));
    for v in r["results"].as_array().into_iter().flatten() {
        let missed: Vec<String> = v["checks"]
            .as_array()
            .into_iter()
            .flatten()
            .filter(|c| c["pass"] != true)
            .map(|c| {
                crate::t!(
                    "osnma-vectors-missed",
                    bar = c["bar"].as_str().unwrap_or("?"),
                    expected = c["expected"].to_string(),
                    observed = c["observed"].to_string()
                )
            })
            .collect();
        println!(
            "{:<28} {:<20} {:<6} {}",
            v["id"].as_str().unwrap_or("?"),
            v["category"].as_str().unwrap_or("?"),
            if v["pass"] == true { "PASS" } else { "FAIL" },
            if missed.is_empty() {
                "-".to_string()
            } else {
                missed.join("; ")
            }
        );
    }
    println!(
        "\n{}",
        crate::t!(
            "osnma-vectors-summary",
            passed = r["passed"].as_u64().unwrap_or(0),
            total = r["total"].as_u64().unwrap_or(0)
        )
    );
}
